function patrol(code:SwarmPeriodic,brief:string,arrival:(counts:number[],tier:number)=>string,notes?:string,extra?:(i:number)=>string){
 const row=SWARM_PERIODIC[code];
 return copy(brief,i=>{
  const counts=row.pack.map(([,amount,width])=>amount[i]*width);
  return `每 ${row.cd[i]} 秒${arrival(counts,i)}，协助作战 ${row.life[i]} 秒。`+
   (row.cap[i]<7?`增援的军衔最高为 ${rankCeiling(row.cap[i])}。`:'')+(extra?.(i)??'');
 },notes);
}

