const allCopy=new Map(ZERG_SWARM_CARDS.map(({short,maxRank})=>{
 const entry=playerCopy[short];
 const effects=Array.from({length:maxRank},(_,i)=>entry.describe(i));
 const details=effects.map((effect,i)=>maxRank===1?effect:numerals[i]+'档　'+effect);
 return [short,{brief:entry.brief,effects,notes:entry.notes,detail:[...details,entry.notes].filter(Boolean).join('\n')}] as const;
}));

export const swarmCardCopy=(short:ZswShort)=>allCopy.get(short)!;
