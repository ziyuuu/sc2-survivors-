import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';

const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const index=JSON.parse(await fs.readFile('deploy/runtime/source-assets.json','utf8'));
if(index.version!==1||!Array.isArray(index.entries)||!index.entries.length)throw Error('Invalid Git runtime catalog');
const checked=new Map(),destinations=new Map();
for(const row of index.entries){
 if(!/^deploy\/runtime\/assets\/[a-f0-9]{64}\.[a-z0-9]+$/.test(row.gitPath)||!/^public\/assets\/[A-Za-z0-9_./-]+$/.test(row.packedFile)||row.packedFile.split('/').includes('..'))throw Error('Invalid Git runtime path');
 if(row.runtime.status!=='available'||row.runtime.url!==row.packedFile.slice(7))throw Error('Invalid runtime record: '+row.runtime.id);
 if(!checked.has(row.gitPath)){
  const bytes=await fs.readFile(row.gitPath);
  if(bytes.length!==row.bytes||sha(bytes)!==row.sha256)throw Error('Git LFS resource missing or corrupt: '+row.gitPath+'; run git lfs pull');
  checked.set(row.gitPath,row.sha256);
 }else if(checked.get(row.gitPath)!==row.sha256)throw Error('Conflicting resource hash');
 const previous=destinations.get(row.packedFile);if(previous&&previous.sha256!==row.sha256)throw Error('Conflicting runtime destination');destinations.set(row.packedFile,row);
}
const generated='// Generated by tools/prepare-assets.mjs. Local assets are never committed.\nexport const RUNTIME_ASSETS = '+JSON.stringify(index.entries.map(e=>e.runtime),null,2)+';\n';
if(sha(generated)!==index.generatedSha256)throw Error('Git runtime catalog checksum differs');
const outputs=[...destinations].map(([file,row])=>({file,sha256:row.sha256,source:row.gitPath}));
outputs.push({file:'src/assets/runtime.generated.ts',sha256:index.generatedSha256,bytes:generated});
const missing=[];
for(const output of outputs){
 const existing=await fs.readFile(output.file).catch(e=>{if(e.code!=='ENOENT')throw e;return null;});
 if(existing&&sha(existing)!==output.sha256)throw Error('Preserving a locally changed runtime file: '+output.file+'; rebuild or update the baseline explicitly');
 if(!existing)missing.push(output);
}
if(process.argv.includes('--check')&&missing.length)throw Error('Runtime files have not been restored: '+missing.length);
for(const output of missing){await fs.mkdir(path.dirname(output.file),{recursive:true});if(output.source)await fs.copyFile(output.source,output.file);else await fs.writeFile(output.file,output.bytes);}
console.log(JSON.stringify({runtimeRecords:index.entries.length,verifiedFiles:checked.size,restoredFiles:missing.length,release:index.release}));
