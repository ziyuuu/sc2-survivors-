import {loadIntermissionAssets} from './intermission-assets.mjs';
import {loadNativeHudAssets} from './native-hud-assets.mjs';
import {loadMaterialTextures} from './material-textures.mjs';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';

const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const index=JSON.parse(await fs.readFile('deploy/runtime/source-assets.json','utf8'));
if(index.version!==1||!Array.isArray(index.entries)||!index.entries.length)throw Error('Invalid Git runtime catalog');
const checked=new Map(),destinations=new Map();
for(const row of index.entries){
 if(!/^deploy\/runtime\/assets\/[a-f0-9]{64}\.[a-z0-9]+$/.test(row.gitPath)||!/^public\/assets\/[A-Za-z0-9_./-]+$/.test(row.packedFile)||row.packedFile.split('/').includes('..'))throw Error('Invalid Git runtime path');
 if(row.runtime.status!=='available'||row.runtime.url!==row.packedFile.slice(7))throw Error('Invalid runtime record: '+row.runtime.id);
 if(!checked.has(row.gitPath)){
  const bytes=await fs.readFile(row.gitPath);
  if(bytes.length!==row.bytes||sha(bytes)!==row.sha256)throw Error('Git LFS resource missing or corrupt: '+row.gitPath+'; run git lfs pull');
  checked.set(row.gitPath,row.sha256);
 }else if(checked.get(row.gitPath)!==row.sha256)throw Error('Conflicting resource hash');
 const previous=destinations.get(row.packedFile);if(previous&&previous.sha256!==row.sha256)throw Error('Conflicting runtime destination');destinations.set(row.packedFile,row);
}
const generated='// Generated by tools/prepare-assets.mjs. Local assets are never committed.\nexport const RUNTIME_ASSETS = '+JSON.stringify(index.entries.map(e=>e.runtime),null,2)+';\n';
if(sha(generated)!==index.generatedSha256)throw Error('Git runtime catalog checksum differs');
const outputs=[...destinations].map(([file,row])=>({file,sha256:row.sha256,source:row.gitPath}));
outputs.push({file:'src/assets/runtime.generated.ts',sha256:index.generatedSha256,bytes:generated});
const missing=[];
for(const output of outputs){
 const existing=await fs.readFile(output.file).catch(e=>{if(e.code!=='ENOENT')throw e;return null;});
 if(existing&&sha(existing)!==output.sha256)throw Error('Preserving a locally changed runtime file: '+output.file+'; rebuild or update the baseline explicitly');
 if(!existing)missing.push(output);
}
if(process.argv.includes('--check')&&missing.length)throw Error('Runtime files have not been restored: '+missing.length);
for(const output of missing){await fs.mkdir(path.dirname(output.file),{recursive:true});if(output.source)await fs.copyFile(output.source,output.file);else await fs.writeFile(output.file,output.bytes);}
console.log(JSON.stringify({runtimeRecords:index.entries.length,verifiedFiles:checked.size,restoredFiles:missing.length,release:index.release}));
// UI art has its own provenance; never append it to the original SC2 catalog.
const ui=await fs.readFile('deploy/runtime/ui-assets.json','utf8').then(JSON.parse).catch(e=>{if(e.code!=='ENOENT')throw e;return null;});
if(ui){
 if(ui.version!==1||sha((await fs.readFile('src/assets/ui-art.generated.ts','utf8')).replace(/\r\n/g,'\n'))!==ui.generatedSha256)throw Error('UI generated registry differs');
 for(const r of ui.records){
  if(!/^public\/assets\/ui\/[a-f0-9]{64}\.(webp|png)$/.test(r.packedFile)||!r.sourceFile.startsWith('preview/ui-20261003/')||r.sourceFile.split('/').includes('..'))throw Error('Invalid UI resource path');
  if(r.gitPath!=='deploy/runtime/assets/'+r.packedSha256+path.extname(r.sourceFile))throw Error('Invalid Git UI path: '+r.id);
  const gitBytes=await fs.readFile(r.gitPath);if(gitBytes.length!==r.bytes||sha(gitBytes)!==r.packedSha256)throw Error('Git UI asset differs: '+r.id);
  const source=await fs.readFile(r.sourceFile);
  const pointer=source.length<256?source.toString('utf8').match(/^version https:\/\/git-lfs.github.com\/spec\/v1\r?\noid sha256:([a-f0-9]{64})\r?\nsize (\d+)\r?\n?$/):null;
  const sourceMatches=pointer?pointer[1]===r.sourceSha256&&Number(pointer[2])===r.bytes:source.length===r.bytes&&sha(source)===r.sourceSha256;
  if(!sourceMatches||r.sourceSha256!==r.packedSha256)throw Error('UI source changed: '+r.id);
  const current=await fs.readFile(r.packedFile).catch(e=>{if(e.code!=='ENOENT')throw e;return null;});
  if(current&&sha(current)!==r.packedSha256)throw Error('Preserving changed UI asset: '+r.id);
  if(!current){if(process.argv.includes('--check'))throw Error('UI asset not restored: '+r.id);await fs.mkdir(path.dirname(r.packedFile),{recursive:true});await fs.writeFile(r.packedFile,gitBytes);}
 }
 console.log(JSON.stringify({uiResources:ui.records.length,verified:true}));
}

await loadIntermissionAssets({restore:true,check:process.argv.includes('--check')});
await loadNativeHudAssets({restore:true,check:process.argv.includes('--check')});
await loadMaterialTextures({restore:true,check:process.argv.includes('--check')});
