import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';

// Promote the reviewed R21/R22 images without modifying their pixels or originals.
const source='preview/starship-field-ui-20261016-r21',hash=b=>createHash('sha256').update(b).digest('hex');
const resources=JSON.parse(await fs.readFile(source+'/resources.json','utf8')).resources,records=[],images={};
async function retain(file,bytes){
 const old=await fs.readFile(file).catch(e=>{if(e.code!=='ENOENT')throw e;return null;});
 if(old&&!old.equals(bytes))throw Error('Preserving changed resource: '+file);
 if(!old){await fs.mkdir(path.dirname(file),{recursive:true});await fs.writeFile(file,bytes);}
}
for(const r of resources){
 if(images[r.key])throw Error('Duplicate starship image key: '+r.key);
 images[r.key]={};
 for(const variant of ['src','detail']){
  const relative=variant==='src'?r.file:r.detail;if(!relative)continue;
  const original=path.resolve(source,relative),bytes=await fs.readFile(original),sha=hash(bytes),ext=path.extname(original);
  if(sha!==(variant==='src'?r.sha256:r.detailSha256)||!['.png','.webp'].includes(ext))throw Error('Reviewed art differs: '+original);
  const id='ui.starship.'+r.key.replaceAll('/','.')+(variant==='detail'?'.detail':''),gitPath=`deploy/runtime/assets/${sha}${ext}`,url=`assets/ui/starship/${sha}${ext}`;
  await retain(gitPath,bytes);await retain('public/'+url,bytes);
  records.push({id,kind:'ui-art',status:'available',required:true,url,sourceFile:gitPath,gitPath,packedFile:'public/'+url,sourceSha256:sha,packedSha256:sha,bytes:bytes.length,reviewedSource:path.relative(process.cwd(),original).replaceAll('\\','/'),imageKey:r.key,variant});
  images[r.key][variant]=id;
 }
}
if(new Set(records.map(r=>r.id)).size!==records.length)throw Error('Duplicate starship resource ID');
const generated='// Reviewed starship UI art. Generated by tools/prepare-starship-runtime-assets.mjs.\n'+
 'export const STARSHIP_ART_ASSETS = '+JSON.stringify(records.map(({id,kind,status,required,url})=>({id,kind,status,required,url})),null,2)+' as const;\n'+
 'export const STARSHIP_ART_IDS:Record<string,{src:string;detail?:string}> = '+JSON.stringify(images,null,2)+';\n';
await fs.writeFile('src/assets/starship-art.generated.ts',generated);
await fs.writeFile('deploy/runtime/starship-assets.json',JSON.stringify({version:1,source:source+'/resources.json',generatedSha256:hash(generated),records},null,2)+'\n');
console.log(JSON.stringify({keys:resources.length,records:records.length,files:new Set(records.map(r=>r.gitPath)).size,bytes:records.reduce((n,r)=>n+r.bytes,0)}));
