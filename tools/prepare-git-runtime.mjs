import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';

// Snapshot already verified runtime bytes for a fresh Git checkout. No source conversion.
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const records=JSON.parse(await fs.readFile('reports/local/runtime-assets.json','utf8'));
const runtime=records.map(r=>Object.fromEntries(['id','kind','status','url','required','sprite'].filter(k=>r[k]!==undefined).map(k=>[k,r[k]])));
const generated='// Generated by tools/prepare-assets.mjs. Local assets are never committed.\nexport const RUNTIME_ASSETS = '+JSON.stringify(runtime,null,2)+';\n';
if(sha(generated)!==sha(await fs.readFile('src/assets/runtime.generated.ts')))throw Error('Generated runtime catalog differs from source records');
const entries=[],physical=new Map();let added=0,addedBytes=0;
for(let i=0;i<records.length;i++){
 const r=records[i];if(r.status!=='available')throw Error('Cannot freeze an incomplete runtime: '+r.id);
 if(!r.packedFile.startsWith('public/assets/')||r.packedFile.split('/').includes('..'))throw Error('Invalid runtime path: '+r.id);
 const bytes=await fs.readFile(r.packedFile),digest=sha(bytes),gitPath='deploy/runtime/assets/'+digest+path.extname(r.packedFile);
 const existing=await fs.readFile(gitPath).catch(e=>{if(e.code!=='ENOENT')throw e;return null;});
 if(existing&&sha(existing)!==digest)throw Error('Existing Git resource differs: '+gitPath);
 if(!existing){await fs.mkdir(path.dirname(gitPath),{recursive:true});await fs.writeFile(gitPath,bytes);added++;addedBytes+=bytes.length;}
 entries.push({runtime:runtime[i],packedFile:r.packedFile,gitPath,bytes:bytes.length,sha256:digest});physical.set(gitPath,bytes.length);
}
const release=JSON.parse(await fs.readFile('dist/web/web-release.json','utf8'));
await fs.writeFile('deploy/runtime/source-assets.json',JSON.stringify({version:1,release:release.release,generatedSha256:sha(generated),entries},null,2)+'\n');
console.log(JSON.stringify({records:entries.length,files:physical.size,bytes:[...physical.values()].reduce((a,b)=>a+b,0),added,addedBytes}));
