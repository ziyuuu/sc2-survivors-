export type EnemyPrepared={actor:Entity;targetId:number|null;patientId:number|null;witnessId:number;spec:EnemyFixture;case:Case;startedAt:number|null;receipt:any;firstCast?:{kind:string;start:number;at:number};interrupted?:boolean;auraExited?:boolean;autoCast?:boolean};
const position=(u:Entity,x:number,z:number)=>Object.assign(u,{x,z,prev:{x,z},velocity:{x:0,z:0}});
function silent(u:Entity){u.weaponCooldown=1e6;u.nextShotAt=1e6;u.abilityReady=Infinity;u.specialReady=Infinity;u.stoppedUntil=1e6;}

/** Only target setup and command timing are controlled. Enemy level, trait,
 * transformation, targeting, skill packets, status expiry and damage are native. */
export function prepareEnemyFixture(w:World,c:Case,target:string,step=()=>w.step()):EnemyPrepared{
 const spec=c.fixture?.enemy;if(!spec)throw Error('Enemy case lacks a native spawn specification');
 const stamp={stage:spec.stage,progress:(spec.stage-1)/18,density:1 as const},attempts=[];
 let actor:Entity|undefined;
 for(let i=0;i<64;i++){
  const candidate=w.spawnSpecial(c.family as SpecialType,c.actor as EnemyTier,{x:0,z:0},stamp);if(!candidate)throw Error('Native enemy spawn failed');
  attempts.push({id:candidate.id,trait:candidate.lordTrait??null});
  if(!spec.trait||candidate.lordTrait===spec.trait){actor=candidate;break;}w.entities.delete(candidate.id);
 }
 if(!actor)throw Error('Requested lord trait was not generated by the native RNG');
 if(actor.enemyLevel!==spec.level||actor.rank!==1)throw Error('Native enemy level mismatch');
 actor.weaponCooldown=1e6;actor.nextShotAt=1e6;actor.specialReady=Infinity;actor.corrosiveBileReady=Infinity;actor.abilityReady=Infinity;
 const witness=w.addUnit('marine','terran',50,50);silent(witness);
 const prepared:EnemyPrepared={actor,targetId:null,patientId:null,witnessId:witness.id,spec,case:c,startedAt:null,receipt:{scope:'受控敌军场景；目标和旁观单位禁用行动，伤害与技能由生产World执行；需要时仅玩家目标启用诊断锁血。',spawn:{stamp,attempts,selectedId:actor.id,nativeLevel:actor.enemyLevel,rank:actor.rank,trait:actor.lordTrait??null}}};
 if(c.family==='lurker'){
  // Existing native Eye detection keeps the real cloaked body visible without
  // rewriting its cloak flag or adding a custom rendering route.
  w.funShop.levels.eye=1;prepared.receipt.detection='隔离数据启用既有天眼1级；原生隐形与侦测路径保持。';
  const destination=(c.data as {mode?:string}|undefined)?.mode;
  const required=c.action==='mode'?(destination==='lurker'?'lurker_burrowed':'lurker'):(spec.mode??'lurker_burrowed');
  position(witness,0,required==='lurker_burrowed'?7:12);w.hash.rebuild(w.entities.values());
  const before={time:w.time,mode:actor.nativeMode},paused=w.paused;w.paused=false;
  try{
   let steps=0;
   const minimumAge=c.actor==='elite'?0:c.action==='mode'?(destination==='lurker'?7.75:13.75):required==='lurker'?8.05:0;
   while((actor.nativeMode??actor.unitType)!==required||actor.nativeModeUntil!==undefined||w.time-actor.bornAt<minimumAge-1e-7){
    if(++steps>1200)throw Error('Native enemy form preparation timeout');step();if(w.phase!=='battle'||actor.hp<=0)throw Error('Enemy form setup ended the battle');
   }
   prepared.receipt.modePreparation={before,after:{time:w.time,mode:actor.nativeMode,age:w.time-actor.bornAt},steps,scope:c.actor==='elite'?'通过目标在9距离内/外触发原生自动埋地/出土。':'通过原生14秒周期等待指定形态；后续自动变形保持。'};
  }finally{w.paused=paused;}
 }
 if(['attack','skill'].includes(c.action!)&&spec.skill!=='heal'){
  const t=w.addUnit(target==='air'?'mutalisk':target==='shield'?'stalker':'roach','terran',0,4);silent(t);prepared.targetId=t.id;
  if(c.fixture?.targetEdgeDistance!==undefined)t.z=actor.z+actor.unitRadius+t.unitRadius+c.fixture.targetEdgeDistance;
  else if(c.action==='skill')t.z=actor.z+actor.unitRadius+t.unitRadius+3;
  t.prev={x:t.x,z:t.z};
  // Bile may be aimed at a legal air weapon target but only damages ground.
  if(spec.skill==='bile'&&target==='air'){const ground=w.addUnit('roach','terran',t.x,t.z);silent(ground);prepared.receipt.groundWitnessId=ground.id;}
  if(c.family==='lurker')position(witness,50,50);
  setDiagnosticHealthLock(w,true);
 }
 if(spec.skill==='heal'||c.action==='auto-ability'||c.action==='aura'){
  const p=w.addUnit('roach','zerg',-3,0);silent(p);p.hp=p.maxHp*.15;prepared.patientId=p.id;
 }
 if(c.family==='lurker'&&c.actor==='elite'&&spec.mode==='lurker'&&c.action!=='mode')position(witness,0,12);
 w.hash.rebuild(w.entities.values());
 prepared.receipt.setup={actorId:actor.id,targetId:prepared.targetId,patientId:prepared.patientId,witnessId:witness.id,diagnostic:diagnosticHealthLock(w),targetPlane:target};
 return prepared;
}

export function triggerEnemyFixture(w:World,p:EnemyPrepared){
 const {actor:u,case:c}=p;p.startedAt=w.time;p.receipt.trigger={at:w.time,action:c.action};
 if(c.action==='attack'){u.weaponCooldown=0;u.nextShotAt=w.time;u.thinkAt=w.time;}
 if(c.action==='skill'){if(u.unitType==='queen'&&u.enemyTier!=='elite'&&p.spec.skill==='bile')u.corrosiveBileReady=w.time;else u.specialReady=w.time;}
 if(c.action==='auto-ability'){u.abilityReady=w.time;u.energy=u.maxEnergy;}
 if(c.action==='move'){Object.assign(w.anchor,{x:6,z:0});p.receipt.trigger.nativeGoal={x:6,z:0};}
 if(c.action==='mode'&&c.actor==='elite'){
  const mode=(c.data as {mode:string}).mode,witness=w.entities.get(p.witnessId)!;
  position(witness,0,mode==='lurker'?12:7);w.hash.rebuild(w.entities.values());p.receipt.trigger.witness={x:witness.x,z:witness.z};
 }
 if(c.action==='hit')w.hit(u,Math.max(2,u.maxHp*.08),[],1,'terran',.5,0,undefined,false,false,0,true);
 if(c.action==='death')w.hit(u,1e12,[],1,'terran',0,1,undefined,true);
}

export function beforeEnemyStep(w:World,p:EnemyPrepared){
 if(p.startedAt===null)return;
 if(p.spec.interruption&&!p.interrupted&&p.firstCast){
  const when=p.spec.interruption==='before-commit'?p.firstCast.start+.2:p.firstCast.at+.05;
  if(w.time+1e-8>=when){const u=w.entities.get(p.actor.id);if(!u||u.hp<=0)throw Error('Enemy interrupt source already absent');w.hit(u,1e12,[],1,'terran',0,1,undefined,true);p.interrupted=true;p.receipt.interruption={at:w.time,elapsed:w.time-p.startedAt,condition:p.spec.interruption,deathTiming:p.spec.interruption==='before-commit'&&p.spec.skill==='bile'?'after-launch-before-impact':p.spec.interruption,pendingAt:p.firstCast.at,scope:'通过真实伤害杀死施法者；胆汁已在锁定落点时发射，原生已发包保持，其他未提交施法自行取消。'};}
 }
 if(p.case.action==='aura'&&!p.auraExited&&w.time-p.startedAt>=3-1e-8){
  const patient=w.entities.get(p.patientId!)!;const before={x:patient.x,z:patient.z,hp:patient.hp,armor:w.auraArmor.get(patient.id)??0,damage:w.auraDamage.get(patient.id)??0,speed:w.auraAttackSpeed.get(patient.id)??0};
  position(patient,-10,0);w.hash.rebuild(w.entities.values());p.auraExited=true;p.receipt.auraExit={elapsed:w.time-p.startedAt,before,after:{x:patient.x,z:patient.z},scope:'受控受益单位移出原生光环半径；由后续World光环更新撤销。'};
 }
}

export function afterEnemyStep(w:World,p:EnemyPrepared){
 if(p.startedAt===null)return;const u=w.entities.get(p.actor.id);if(!u||u.hp<=0)return;
 if(p.case.action==='skill'&&!p.firstCast){
  const cast=w.enemySpecials.casts.find(c=>c.source===u.id);
  if(cast){p.firstCast={kind:cast.kind,start:w.time,at:cast.at};p.receipt.firstCast=structuredClone(cast);u.specialReady=Infinity;u.corrosiveBileReady=Infinity;}
  else if(p.spec.skill==='heal'&&(u.lastSkillAt??-Infinity)>=p.startedAt){p.firstCast={kind:'heal',start:w.time,at:w.time};p.receipt.firstCast={kind:'heal',at:w.time,patientHp:w.entities.get(p.patientId!)?.hp};u.specialReady=Infinity;}
 }
 if(p.case.action==='auto-ability'&&!p.autoCast&&(u.abilityReady??0)>w.time&&u.abilityReady!==Infinity){p.autoCast=true;p.receipt.autoCast={at:w.time,spells:structuredClone(w.expedition.spells)};u.abilityReady=Infinity;}
}

export function enemyFixtureSnapshot(w:World,p:EnemyPrepared){
 const u=w.entities.get(p.actor.id),patient=p.patientId===null?undefined:w.entities.get(p.patientId),s=w.enemySpecials;
 const body=(e:Entity|undefined)=>e?{id:e.id,hp:e.hp,maxHp:e.maxHp,mode:e.nativeMode,desiredMode:e.desiredNativeMode,modeUntil:e.nativeModeUntil,level:e.enemyLevel,rank:e.rank,trait:e.lordTrait,tier:e.enemyTier,name:e.enemyName,plane:unitData(e).targetType,activeWeapon:e.activeWeapon,attackRange:e.attackRange,shotInterval:e.shotInterval,attackPeriod:e.attackPeriod,moveSpeed:e.moveSpeed,shots:e.shotSequence,x:e.x,z:e.z,visible:w.visibleTo(e,'terran'),armorAura:w.auraArmor.get(e.id)??0,damageAura:w.auraDamage.get(e.id)??0,speedAura:w.auraAttackSpeed.get(e.id)??0}:null;
 return {spec:p.spec,receipt:p.receipt,actor:body(u),patient:body(patient),groundWitness:body(w.entities.get(p.receipt.groundWitnessId)),casts:structuredClone(s.casts),missiles:s.missiles.map(m=>({...m,hits:[...m.hits]})),charges:[...s.charges].map(([id,c])=>({id,...c,hits:[...c.hits]})),acidZones:structuredClone(s.acidZones),corrosionZones:structuredClone(w.corrosionZones),statuses:w.statuses.snapshot(),diagnostic:diagnosticHealthLock(w)};
}
